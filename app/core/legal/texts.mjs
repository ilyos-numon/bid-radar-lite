export const LEGAL_DEFAULT_VERSION = '2026-11-03';
const DRAFT_NOTICE = '초안 — 시행 전 법률 검토 필요';

/** @returns {{ terms: string, privacy: string }} */
export function versions(env = {}) {
  return {
    terms: String(env?.LEGAL_TERMS_VERSION ?? '').trim() || LEGAL_DEFAULT_VERSION,
    privacy: String(env?.LEGAL_PRIVACY_VERSION ?? '').trim() || LEGAL_DEFAULT_VERSION,
  };
}

function draft(env) {
  return String(env?.LEGAL_DRAFT_NOTICE ?? '') !== '0' ? notice(DRAFT_NOTICE, { kind: 'warn', role: 'note' }) : '';
}

/** [제목, [문단...]] 목록 → 조항 HTML. 문단 안 글자는 모두 esc */
function articles(list) {
  return list
    .map(([title, paras]) => `<section class="legal-article"><h2>${esc(title)}</h2>${paras.map((p) => `<p>${esc(p)}</p>`).join('')}</section>`)
    .join('');
}

