-- 코어 테이블. 모듈 테이블은 각 모듈의 schema.sql 에 <id>_ 접두로 둔다.
-- Postgres 방언. 모든 테이블은 workspace_id 로 시작하고 키도 workspace_id 로 시작한다.
CREATE TABLE IF NOT EXISTS settings (
  workspace_id uuid NOT NULL DEFAULT (current_setting('app.workspace_id', true))::uuid,
  key text NOT NULL,
  value text NOT NULL,
  PRIMARY KEY (workspace_id, key)
);

CREATE TABLE IF NOT EXISTS members (
  workspace_id uuid NOT NULL DEFAULT (current_setting('app.workspace_id', true))::uuid,
  id integer GENERATED BY DEFAULT AS IDENTITY,
  name text NOT NULL,
  role text NOT NULL CHECK (role IN ('owner', 'staff')),
  token_hash text NOT NULL,
  created_at text NOT NULL,
  PRIMARY KEY (workspace_id, id),
  UNIQUE (workspace_id, token_hash)
);

CREATE TABLE IF NOT EXISTS sources (
  workspace_id uuid NOT NULL DEFAULT (current_setting('app.workspace_id', true))::uuid,
  id text NOT NULL,
  type text NOT NULL,
  name text NOT NULL,
  enabled integer NOT NULL DEFAULT 1,
  config text NOT NULL,
  created_at text NOT NULL,
  PRIMARY KEY (workspace_id, id)
);

CREATE TABLE IF NOT EXISTS source_runs (
  workspace_id uuid NOT NULL DEFAULT (current_setting('app.workspace_id', true))::uuid,
  id integer GENERATED BY DEFAULT AS IDENTITY,
  source_id text NOT NULL,
  ran_at text NOT NULL,
  ok integer NOT NULL,
  count integer NOT NULL DEFAULT 0,
  error text,
  PRIMARY KEY (workspace_id, id)
);

CREATE TABLE IF NOT EXISTS bids (
  workspace_id uuid NOT NULL DEFAULT (current_setting('app.workspace_id', true))::uuid,
  bid_id text NOT NULL,
  source_id text NOT NULL,
  title text NOT NULL,
  org text,
  deadline text,
  budget bigint,
  url text,
  raw text NOT NULL,
  first_seen text NOT NULL,
  PRIMARY KEY (workspace_id, bid_id)
);

CREATE TABLE IF NOT EXISTS bid_texts (
  workspace_id uuid NOT NULL DEFAULT (current_setting('app.workspace_id', true))::uuid,
  bid_id text NOT NULL,
  status text NOT NULL CHECK (status IN ('ok', 'none', 'failed')),
  text text NOT NULL DEFAULT '',
  fetched_at text NOT NULL,
  PRIMARY KEY (workspace_id, bid_id)
);

CREATE TABLE IF NOT EXISTS matches (
  workspace_id uuid NOT NULL DEFAULT (current_setting('app.workspace_id', true))::uuid,
  date text NOT NULL,
  bid_id text NOT NULL,
  kind text NOT NULL CHECK (kind IN ('match', 'maybe')),
  rank integer NOT NULL,
  reasons text NOT NULL,
  PRIMARY KEY (workspace_id, date, bid_id)
);

CREATE TABLE IF NOT EXISTS notifications (
  workspace_id uuid NOT NULL DEFAULT (current_setting('app.workspace_id', true))::uuid,
  id integer GENERATED BY DEFAULT AS IDENTITY,
  kind text NOT NULL,
  date text NOT NULL,
  payload text NOT NULL,
  created_at text NOT NULL,
  PRIMARY KEY (workspace_id, id)
);

CREATE TABLE IF NOT EXISTS bid_details (
  workspace_id uuid NOT NULL DEFAULT (current_setting('app.workspace_id', true))::uuid,
  bid_id text NOT NULL,
  kind text NOT NULL DEFAULT 'new',
  opening_at text,
  budget_basis text,
  norm text NOT NULL DEFAULT '{}',   -- NormalizedBid 중 amounts·limits·noticeOrg·postedAt JSON
  last_seen text NOT NULL,
  PRIMARY KEY (workspace_id, bid_id)
);
CREATE TABLE IF NOT EXISTS bid_changes (
  workspace_id uuid NOT NULL DEFAULT (current_setting('app.workspace_id', true))::uuid,
  id integer GENERATED BY DEFAULT AS IDENTITY,
  bid_id text NOT NULL,
  seen_at text NOT NULL,
  field text NOT NULL CHECK (field IN ('deadline', 'kind', 'budget', 'openingAt')),
  old text,
  new text,
  PRIMARY KEY (workspace_id, id)
);
CREATE INDEX IF NOT EXISTS bid_changes_seen ON bid_changes (workspace_id, seen_at);
CREATE TABLE IF NOT EXISTS collect_days (
  workspace_id uuid NOT NULL DEFAULT (current_setting('app.workspace_id', true))::uuid,
  source_id text NOT NULL,
  day text NOT NULL,                 -- 'YYYY-MM-DD' (KST)
  ok integer NOT NULL,
  pages integer NOT NULL DEFAULT 0,
  count integer NOT NULL DEFAULT 0,
  truncated integer NOT NULL DEFAULT 0,
  ran_at text NOT NULL,
  PRIMARY KEY (workspace_id, source_id, day)
);

CREATE TABLE IF NOT EXISTS bid_links (
  workspace_id uuid NOT NULL DEFAULT (current_setting('app.workspace_id', true))::uuid,
  prestd_id text NOT NULL,                       -- 'PS<bfSpecRgstNo>-000'
  notice_no text NOT NULL,                       -- bidNtceNo (차수 없음)
  origin text NOT NULL CHECK (origin IN ('prestd', 'notice')),
  seen_at text NOT NULL,
  PRIMARY KEY (workspace_id, prestd_id, notice_no)
);
CREATE INDEX IF NOT EXISTS bid_links_notice ON bid_links (workspace_id, notice_no);

-- 회사별 작업 실행 기록 (멱등 키: workspace_id, job, date)
CREATE TABLE IF NOT EXISTS job_runs (
  workspace_id uuid NOT NULL DEFAULT (current_setting('app.workspace_id', true))::uuid,
  job text NOT NULL CHECK (job IN ('daily','reminders','support')),
  date text NOT NULL,
  run_id text NOT NULL,
  status text NOT NULL CHECK (status IN ('queued','running','done','failed','dead')),
  attempt integer NOT NULL DEFAULT 0,
  started_at text, finished_at text, error_code text,
  PRIMARY KEY (workspace_id, job, date)
);

-- 알림 발송 기록 (중복 방지: workspace_id, kind, date)
CREATE TABLE IF NOT EXISTS notification_deliveries (
  workspace_id uuid NOT NULL DEFAULT (current_setting('app.workspace_id', true))::uuid,
  id integer GENERATED BY DEFAULT AS IDENTITY,
  kind text NOT NULL, date text NOT NULL, run_id text NOT NULL,
  target_host text, status text NOT NULL CHECK (status IN ('sending','sent','failed','skipped')),
  http_status integer, error_code text, sent_at text, created_at text NOT NULL,
  PRIMARY KEY (workspace_id, id), UNIQUE (workspace_id, kind, date)
);
