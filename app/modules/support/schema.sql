-- 지원사업 모듈 전용 테이블. 입찰 공고 테이블과 섞지 않는다.
CREATE TABLE IF NOT EXISTS support_items (
  workspace_id uuid NOT NULL DEFAULT (current_setting('app.workspace_id', true))::uuid,
  id text NOT NULL,
  title text NOT NULL,
  org text NOT NULL DEFAULT '',
  apply_end text NOT NULL DEFAULT '',
  url text NOT NULL DEFAULT '',
  summary text NOT NULL DEFAULT '',
  region text NOT NULL DEFAULT '',
  first_seen text NOT NULL,
  matched_reasons text NOT NULL DEFAULT '[]',
  PRIMARY KEY (workspace_id, id)
);
CREATE TABLE IF NOT EXISTS support_runs (
  workspace_id uuid NOT NULL DEFAULT (current_setting('app.workspace_id', true))::uuid,
  id integer GENERATED BY DEFAULT AS IDENTITY,
  ran_at text NOT NULL,
  ok integer NOT NULL,
  count integer NOT NULL DEFAULT 0,
  error text,
  PRIMARY KEY (workspace_id, id)
);
