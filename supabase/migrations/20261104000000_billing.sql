-- Billing platform tables (subscriptions, payments, billing_events, billing_jobs) and Vault RPCs for billing keys.
-- Platform tables like rate_limits: no RLS, direct grants to app_worker, revoked from anon/authenticated.
-- source: app/core/billing/schema.sql (kept verbatim; tests/unit/billing-core.test.mjs checks for drift)
CREATE TABLE IF NOT EXISTS subscriptions (
  workspace_id uuid PRIMARY KEY,
  plan text NOT NULL CHECK (plan IN ('trial','starter','team')),
  status text NOT NULL CHECK (status IN ('trialing','active','past_due','canceled','expired')),
  customer_key text NOT NULL UNIQUE,
  trial_ends_at timestamptz,
  current_period_end timestamptz,
  next_charge_at timestamptz,
  cancel_at_period_end boolean NOT NULL DEFAULT false,
  retry_count integer NOT NULL DEFAULT 0,
  card_summary text,
  billing_secret_id uuid,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS payments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id uuid NOT NULL,
  order_id text NOT NULL UNIQUE,
  payment_key text,
  plan text NOT NULL,
  amount integer NOT NULL,
  status text NOT NULL CHECK (status IN ('ready','paid','failed','canceled')),
  fail_code text,
  approved_at timestamptz,
  period_start timestamptz,
  period_end timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS billing_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider text NOT NULL DEFAULT 'toss',
  event_key text NOT NULL UNIQUE,
  event_type text NOT NULL,
  payload jsonb NOT NULL,
  received_at timestamptz NOT NULL DEFAULT now(),
  processed_at timestamptz,
  result text
);
CREATE TABLE IF NOT EXISTS billing_jobs (
  run_date date PRIMARY KEY,
  started_at timestamptz NOT NULL DEFAULT now(),
  finished_at timestamptz,
  charged integer NOT NULL DEFAULT 0,
  failed integer NOT NULL DEFAULT 0,
  expired integer NOT NULL DEFAULT 0
);

alter table public.subscriptions add constraint subscriptions_ws_fk
  foreign key (workspace_id) references public.workspaces(id) on delete cascade;
alter table public.payments add constraint payments_ws_fk
  foreign key (workspace_id) references public.workspaces(id) on delete cascade;

create index if not exists payments_ws_created_idx on public.payments (workspace_id, created_at desc);

revoke all on public.subscriptions, public.payments, public.billing_events, public.billing_jobs from public, anon, authenticated;
grant select, insert, update, delete on public.subscriptions, public.payments, public.billing_events, public.billing_jobs to app_worker;
grant usage, select on all sequences in schema public to app_worker;

-- ---------------------------------------------------------------------------
-- Billing key storage in Supabase Vault (service_role only)
-- ---------------------------------------------------------------------------
create or replace function public.billing_set_key(p_ws uuid, p_key text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_found boolean;
  v_secret uuid;
begin
  select true, s.billing_secret_id into v_found, v_secret
    from public.subscriptions s
    where s.workspace_id = p_ws
    for update;
  if v_found is null then
    raise exception 'NO_SUBSCRIPTION' using errcode = 'P0002';
  end if;
  if v_secret is null or not exists (select 1 from vault.secrets v where v.id = v_secret) then
    v_secret := vault.create_secret(p_key, null, 'billing ' || p_ws::text);
  else
    perform vault.update_secret(v_secret, p_key);
  end if;
  update public.subscriptions s
    set billing_secret_id = v_secret, updated_at = now()
    where s.workspace_id = p_ws;
end;
$$;

create or replace function public.billing_get_key(p_ws uuid)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_key text;
begin
  select d.decrypted_secret into v_key
    from public.subscriptions s
    join vault.decrypted_secrets d on d.id = s.billing_secret_id
    where s.workspace_id = p_ws;
  return v_key;
end;
$$;

create or replace function public.billing_delete_key(p_ws uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_secret uuid;
begin
  select s.billing_secret_id into v_secret
    from public.subscriptions s
    where s.workspace_id = p_ws
    for update;
  if v_secret is not null then
    delete from vault.secrets v where v.id = v_secret;
  end if;
  update public.subscriptions s
    set billing_secret_id = null, card_summary = null, updated_at = now()
    where s.workspace_id = p_ws;
end;
$$;

revoke all on function public.billing_set_key(uuid, text) from public, anon, authenticated;
revoke all on function public.billing_get_key(uuid) from public, anon, authenticated;
revoke all on function public.billing_delete_key(uuid) from public, anon, authenticated;
grant execute on function public.billing_set_key(uuid, text) to service_role;
grant execute on function public.billing_get_key(uuid) to service_role;
grant execute on function public.billing_delete_key(uuid) to service_role;

-- Removing a subscriptions row (directly or through a workspace cascade) deletes its Vault secret.
create or replace function public.subscriptions_delete_secret()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if old.billing_secret_id is not null then
    delete from vault.secrets s where s.id = old.billing_secret_id;
  end if;
  return old;
end;
$$;
revoke all on function public.subscriptions_delete_secret() from public, anon, authenticated;

create trigger subscriptions_delete_secret
  after delete on public.subscriptions
  for each row execute function public.subscriptions_delete_secret();
