-- Legal notices: terms/privacy versions and signup consents (platform tables, not tenant tables).
-- Body below is app/core/legal/schema.sql verbatim; grants follow the rate_limits pattern.

-- 법적 고지 플랫폼 표: 약관 버전과 동의 기록. 테넌트 표가 아니다(workspace_id 없음, RLS 없음).
-- user_id FK 없음 — auth.users 는 PGlite 에 없다.
CREATE TABLE IF NOT EXISTS legal_versions (
  doc text NOT NULL CHECK (doc IN ('terms','privacy')),
  version text NOT NULL,
  effective_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (doc, version)
);
CREATE TABLE IF NOT EXISTS consents (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid,
  email text NOT NULL,
  doc text NOT NULL CHECK (doc IN ('terms','privacy')),
  version text NOT NULL,
  agreed_at timestamptz NOT NULL DEFAULT now(),
  ip_hash text,
  user_agent text
);
CREATE INDEX IF NOT EXISTS consents_user_doc ON consents (user_id, doc, version);

revoke all on public.legal_versions from public, anon, authenticated;
revoke all on public.consents from public, anon, authenticated;
revoke all on sequence public.consents_id_seq from public, anon, authenticated;
grant select, insert, update, delete on public.legal_versions to app_worker;
grant select, insert, update, delete on public.consents to app_worker;
grant usage, select on sequence public.consents_id_seq to app_worker;
